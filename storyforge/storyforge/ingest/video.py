"""Anything yt-dlp understands: metadata, subtitles (manual, then automatic) or transcribed audio."""
from __future__ import annotations

import functools
import glob
import os

from ..schema import Chapter, Source, SourceImage, renumber
from . import IngestError, Options, audio, subtitles
from .clean import normalize_ws

# Extractors for sites whose pages are only a player: a failed extraction should not fall back to
# reading the page as an article.
VIDEO_ONLY = ("Youtube", "Vimeo", "Dailymotion", "TikTok", "Twitch", "Loom", "Wistia", "Rumble")
YOUTUBE_AUTO_NOTE = "captions are auto-generated by the video platform (automatic speech recognition)"


@functools.lru_cache(maxsize=1)
def _extractors() -> tuple:
    from yt_dlp.extractor import gen_extractor_classes
    return tuple(ie for ie in gen_extractor_classes() if ie.ie_key() != "Generic")


def extractor_for(url: str) -> str | None:
    """Key of the first non-generic yt-dlp extractor that accepts ``url``."""
    return next((ie.ie_key() for ie in _extractors() if ie.suitable(url)), None)


def is_supported(url: str) -> bool:
    return extractor_for(url) is not None


def is_video_only(url: str) -> bool:
    key = extractor_for(url) or ""
    return key.startswith(VIDEO_ONLY)


def _ydl(opts: Options, **params):
    import yt_dlp
    return yt_dlp.YoutubeDL({
        "quiet": True, "no_warnings": True, "noprogress": True, "socket_timeout": 30,
        "retries": 3, "extractor_retries": 3, "noplaylist": True,
        "outtmpl": os.path.join(opts.workdir, "%(id)s.%(ext)s"), **params})


def choose_subtitles(info: dict, language: str) -> tuple[str, bool] | None:
    """``(track language, is_automatic)``: manual before automatic, requested language before the video's own."""
    wanted = [language] + ([info["language"]] if info.get("language") not in (None, language) else [])
    for auto, key in ((False, "subtitles"), (True, "automatic_captions")):
        tracks = [t for t, fmts in (info.get(key) or {}).items() if fmts and t != "live_chat"]
        for lang in wanted:
            candidates = ([f"{lang}-orig", lang] if auto else [lang]) + sorted(
                t for t in tracks if t.startswith(f"{lang}-"))
            for c in candidates:
                if c in tracks:
                    return c, auto
    return None


def from_info(info: dict, segments: list, notes: list[str], language: str) -> Source:
    """A Source from yt-dlp metadata and already-built segments."""
    date = info.get("upload_date") or ""
    thumb = info.get("thumbnail")
    return Source(
        kind="audio" if info.get("vcodec") == "none" else "video",
        title=normalize_ws(info.get("title") or "") or "Untitled video",
        segments=renumber(segments),
        creator=normalize_ws(info.get("channel") or info.get("uploader") or info.get("creator") or ""),
        url=info.get("webpage_url") or info.get("original_url"),
        published=f"{date[:4]}-{date[4:6]}-{date[6:8]}" if len(date) == 8 else None,
        duration_s=float(info["duration"]) if info.get("duration") else None,
        description=(info.get("description") or "").strip(),
        language=language,
        chapters=[Chapter(normalize_ws(c.get("title") or ""), float(c.get("start_time") or 0))
                  for c in info.get("chapters") or [] if c.get("title")],
        images=[SourceImage(url=thumb, caption="Video thumbnail")] if thumb else [],
        notes=notes)


def subtitle_notes(info: dict, lang: str, auto: bool) -> list[str]:
    notes = [YOUTUBE_AUTO_NOTE] if auto else [f"captions are the uploader's subtitles ({lang})"]
    if auto and info.get("language") and not lang.startswith(info["language"]):
        notes.append(f"captions are machine-translated from {info['language']} into {lang}")
    return notes


def from_subtitle_file(info: dict, path: str, lang: str, auto: bool) -> Source:
    """A Source from yt-dlp metadata and one downloaded subtitle file."""
    with open(path, encoding="utf-8", errors="replace") as f:
        segments, parse_notes = subtitles.to_segments(f.read(), "srt" if path.endswith(".srt") else "vtt")
    if not segments:
        raise IngestError(f"subtitle file {path} contains no cues")
    notes = subtitle_notes(info, lang, auto)
    notes += [n for n in parse_notes if not auto or n != subtitles.AUTO_NOTE]
    return from_info(info, segments, notes, lang.split("-")[0])


def ingest_video(url: str, opts: Options) -> Source:
    """Metadata and subtitles via yt-dlp; download audio and transcribe only when there are none."""
    import yt_dlp

    try:
        with _ydl(opts, skip_download=True) as ydl:
            info = ydl.extract_info(url, download=False)
    except yt_dlp.utils.DownloadError as e:
        raise IngestError(f"yt-dlp could not read {url}: {e}") from e
    if info.get("_type") == "playlist":
        raise IngestError(f"{url} is a playlist or channel; pass the URL of a single video")

    track = choose_subtitles(info, opts.language)
    if track:
        lang, auto = track
        with _ydl(opts, skip_download=True, writesubtitles=not auto, writeautomaticsub=auto,
                  subtitleslangs=[lang], subtitlesformat="vtt/srt/best") as ydl:
            result = ydl.process_ie_result(ydl.sanitize_info(info, remove_private_keys=True), download=True)
        sub = ((result or {}).get("requested_subtitles") or {}).get(lang) or {}
        path = sub.get("filepath")
        if path and path.endswith((".vtt", ".srt")) and os.path.exists(path):
            return from_subtitle_file(info, path, lang, auto)

    audio.pick_engine(opts.transcribe)  # fail before a long download if no engine is installed
    with _ydl(opts, format="bestaudio/best") as ydl:
        result = ydl.process_ie_result(ydl.sanitize_info(info, remove_private_keys=True), download=True)
    downloads = (result or {}).get("requested_downloads") or []
    if not downloads or not os.path.exists(downloads[0].get("filepath", "")):
        raise IngestError(f"yt-dlp found no subtitles and could not download audio for {url}")
    segments, notes = audio.transcribe(downloads[0]["filepath"], opts)
    return from_info(info, segments, ["no subtitles available", *notes], opts.language)


def from_info_json(path: str, info: dict, opts: Options) -> Source:
    """A yt-dlp ``.info.json`` plus the subtitle (or media) file saved next to it."""
    stem = path[: -len(".info.json")] if path.endswith(".info.json") else os.path.splitext(path)[0]
    track = choose_subtitles(info, opts.language)
    for lang, auto in ([track] if track else []) + [(None, False)]:
        pattern = f"{glob.escape(stem)}.{glob.escape(lang) if lang else '*'}.vtt"
        found = sorted(glob.glob(pattern)) + sorted(glob.glob(pattern[:-4] + ".srt"))
        if found:
            sub_lang = lang or found[0][len(stem) + 1:].rsplit(".", 1)[0]
            is_auto = auto if lang else sub_lang not in (info.get("subtitles") or {})
            return from_subtitle_file(info, found[0], sub_lang, is_auto)
    media = [p for p in glob.glob(glob.escape(stem) + ".*")
             if os.path.splitext(p)[1].lower() in audio.AUDIO_EXTS | audio.VIDEO_EXTS]
    if media:
        segments, notes = audio.transcribe(media[0], opts)
        return from_info(info, segments, notes, opts.language)
    raise IngestError(f"no subtitles or media next to {path} (looked for {os.path.basename(stem)}.<lang>.vtt); "
                      f"pass the video URL ({info.get('webpage_url') or 'see the info.json'}) instead")
