"""Original structured score for an episode: sections, stems, motif. Pure NumPy, composed procedurally in this repo.

The score follows the story, not a loop. Each scene belongs to a section:
  A  hook          - a held, intriguing chord and the series motif, quiet enough to leave the first sentence clear
  B  investigation - a soft heartbeat pulse and a breathing texture enter; discovery
  C  questions     - harmony darkens (minor second, tritone), pulse firms, metallic resonances swell
  D  cliffhanger   - a rising swell into one controlled impact, then an unresolved cluster that is left hanging
  E  exit          - a last, incomplete statement of the motif and an intentional fade that ends with the picture
Stems are returned separately (ambience, pulse, motif, metal, impacts) so the mixer can duck each one differently.

Phone speakers reproduce little below ~250 Hz, so every section keeps audible mid-range content (piano, metal,
breathing noise band) instead of relying on sub-bass, which caused silent-sounding gaps on phones in earlier episodes.

Everything here is original: the motif, harmony and sound design are generated by this code. No samples are used.
"""
from __future__ import annotations
import math
import numpy as np
from .audio import SR, add, env

# series identity: a restrained five-note motif (semitones from the key root, beats), deliberately unresolved
MOTIF = [(12, 1.0), (15, 0.5), (14, 1.25), (7, 1.0), (8, 1.75)]
SECTION_LEVEL = {"A": 0.55, "B": 0.62, "C": 0.8, "D": 1.0, "E": 0.5}


def smooth(x: np.ndarray, k: int) -> np.ndarray:
    """Centred moving average of length k via a running sum: O(n), identical to np.convolve(x, ones(k)/k, 'same')."""
    k = max(1, int(k)); c = np.concatenate([[0.0], np.cumsum(x, dtype=np.float64)])
    lo = np.clip(np.arange(len(x)) - k // 2, 0, len(x)); hi = np.clip(np.arange(len(x)) + (k - 1) // 2 + 1, 0, len(x))
    return ((c[hi] - c[lo]) / k).astype(np.float32)


def _rng(seed: int, salt: int) -> np.random.Generator:
    return np.random.default_rng((seed * 7919 + salt) & 0xFFFFFFFF)


def bandpass(x: np.ndarray, lo: float, hi: float) -> np.ndarray:
    X = np.fft.rfft(x); f = np.fft.rfftfreq(len(x), 1 / SR)
    X *= 1 / (1 + (lo / np.maximum(f, 1)) ** 4) / (1 + (f / hi) ** 4)
    return np.fft.irfft(X, len(x)).astype(np.float32)


def reverb(x: np.ndarray, seconds: float = 2.8, seed: int = 1, damp: float = 3500) -> np.ndarray:
    """Convolution with a decaying, darkened noise tail (a simple, smooth room)."""
    n = int(seconds * SR); t = np.arange(n) / SR
    ir = _rng(seed, 99).standard_normal(n).astype(np.float32) * np.exp(-t * 6.9 / seconds)
    ir = bandpass(ir, 120, damp); ir /= np.sqrt(np.sum(ir ** 2)) + 1e-9
    m = 1 << int(math.ceil(math.log2(len(x) + n)))
    y = np.fft.irfft(np.fft.rfft(x, m) * np.fft.rfft(ir, m), m)[: len(x)]
    return y.astype(np.float32)


def piano(freq: float, dur: float, amp: float = 0.3, seed: int = 1) -> np.ndarray:
    """Felt-piano voice: slightly inharmonic partials, faster decay for upper partials, soft hammer."""
    n = int(dur * SR); t = np.arange(n) / SR; B = 0.0004; x = np.zeros(n, np.float32)
    for k in range(1, 9):
        fk = k * freq * math.sqrt(1 + B * k * k)
        if fk > 9000:
            break
        x += (np.sin(2 * np.pi * fk * t + 0.3 * k) * np.exp(-t * (0.7 + 0.55 * k)) / k ** 1.35).astype(np.float32)
    ham = _rng(seed, int(freq)).standard_normal(min(n, int(0.012 * SR))).astype(np.float32) * np.exp(-np.arange(min(n, int(0.012 * SR))) / SR * 300)
    x[: len(ham)] += 0.05 * bandpass(np.pad(ham, (0, 0)), 500, 3000)[: len(ham)]
    x *= (1 - np.exp(-t * 250)) * env(n, 0.002, 0.05, 1.0, min(0.6, dur * 0.4))
    return (amp * x).astype(np.float32)


def metal(freq: float, dur: float, amp: float = 0.2, bowed: bool = True) -> np.ndarray:
    """Inharmonic metal resonance: bowed (slow swell) or struck."""
    n = int(dur * SR); t = np.arange(n) / SR; x = np.zeros(n, np.float32)
    for r, a in [(1.0, 1.0), (2.41, 0.55), (3.93, 0.35), (5.42, 0.22), (6.81, 0.14)]:
        for d in (-0.6, 0.6):   # detuned pairs give a slow beating shimmer
            x += (a * 0.5 * np.sin(2 * np.pi * (freq * r + d) * t)).astype(np.float32)
    shape = env(n, min(1.6, dur * 0.4), 0.3, 0.8, min(1.5, dur * 0.4)) if bowed else np.exp(-t * 1.6) * (1 - np.exp(-t * 800))
    return (amp * x * shape).astype(np.float32)


def boom(amp: float = 0.6, seed: int = 1) -> np.ndarray:
    """Controlled impact: pitch-dropping sub, a mid-band body thud (audible on phones) and a short metallic ring."""
    n = int(2.2 * SR); t = np.arange(n) / SR
    sub = np.sin(2 * np.pi * np.cumsum(32 + 38 * np.exp(-t * 7)) / SR) * np.exp(-t * 2.6)
    body = bandpass(_rng(seed, 7).standard_normal(n).astype(np.float32), 160, 1400) * np.exp(-t * 14) * 0.9
    ring = metal(196.0, 2.2, 0.35, bowed=False)
    return (amp * (0.9 * sub + body + ring)).astype(np.float32)


def riser(dur: float, amp: float = 0.25, seed: int = 1) -> np.ndarray:
    """Noise swell sweeping upward in steps (crossfaded bands) with a rising cluster underneath."""
    n = int(dur * SR); t = np.arange(n) / SR; noise = _rng(seed, 11).standard_normal(n).astype(np.float32)
    bands = [(250, 700), (500, 1300), (900, 2400), (1600, 4200)]; out = np.zeros(n, np.float32)
    for i, (lo, hi) in enumerate(bands):
        c = (i + 0.5) / len(bands); w = np.clip(1 - np.abs(t / dur - c) * len(bands), 0, 1)
        out += bandpass(noise, lo, hi) * w
    cl = sum(np.sin(2 * np.pi * np.cumsum(f0 * (1 + 0.5 * (t / dur) ** 2)) / SR) for f0 in (293.66, 311.13, 440.0)) / 3
    return (amp * (0.6 * out + 0.4 * cl) * (t / dur) ** 2.2).astype(np.float32)


def sections_for(ep: dict, tl: list) -> list[str]:
    """Section per scene: scene['section'] if set, otherwise A first, E last, D before it, C for the last ~third."""
    n = len(tl); out = []
    for i, sc in enumerate(ep["scenes"]):
        if sc.get("section"):
            out.append(sc["section"]); continue
        out.append("A" if i == 0 else "E" if i == n - 1 else "D" if i == n - 2 else "C" if i >= int(n * 0.62) else "B")
    return out


def compose_score(ep: dict, tl: list, total: float, seed: int = 1) -> dict:
    cfg = ep.get("score", {}); root = float(cfg.get("root_hz", 146.83)); bpm = float(cfg.get("bpm", 66)); beat = 60 / bpm
    n = int(total * SR) + 1; t = np.arange(n) / SR
    secs = sections_for(ep, tl)
    # intensity curve per section, smoothed so sections flow into each other
    lev = np.zeros(n, np.float32); sec_at = np.empty(n, dtype="<U1")
    for s, k in zip(tl, secs):
        a, b = int(s["start"] * SR), min(n, int(s["end"] * SR) + 1); lev[a:b] = SECTION_LEVEL[k]; sec_at[a:b] = k
    k_ = int(1.6 * SR); lev = smooth(lev, k_)
    st = {k: np.zeros(n, np.float32) for k in ("ambience", "pulse", "motif", "metal", "impacts")}
    hz = lambda semi: root * 2 ** (semi / 12)

    # --- ambience: dark detuned drone (D + A), a breathing mid noise band, faint glass harmonics; colour darkens in C/D
    rng = _rng(seed, 1)
    drone = sum(np.sin(2 * np.pi * hz(s0) / 2 * (1 + d) * t + p) for s0, d, p in [(0, 0, 0), (0, 0.0021, 1.1), (7, 0.0013, 2.3), (12, -0.0017, 0.4)])
    drone = drone + 0.35 * np.sign(np.sin(2 * np.pi * hz(0) / 2 * t)) * 0.3
    drone = bandpass(drone.astype(np.float32), 60, 900) * 0.16
    breath = bandpass(rng.standard_normal(n).astype(np.float32), 380, 1700) * (0.5 + 0.5 * np.sin(2 * np.pi * t / 7.3) ** 2) * 0.05
    glass = (np.sin(2 * np.pi * hz(24) * t) + 0.6 * np.sin(2 * np.pi * hz(31) * t)) * (0.5 + 0.5 * np.sin(2 * np.pi * t / 11.0)) * 0.012
    dark = smooth(np.isin(sec_at, ["C", "D"]).astype(np.float32), k_)
    tension = bandpass((np.sin(2 * np.pi * hz(1) * t) + np.sin(2 * np.pi * hz(6) * t)).astype(np.float32), 100, 2000) * 0.03 * dark
    pad = np.zeros(n, np.float32)
    for s0, ph0 in [(12, 0.0), (15, 1.3), (19, 2.1), (24, 0.7)]:   # D4 F4 A4 D5 (with a slow, uneven swell per voice)
        pad += (np.sin(2 * np.pi * hz(s0) * t + ph0) + 0.3 * np.sin(2 * np.pi * hz(s0) * 2.003 * t)) * (0.6 + 0.4 * np.sin(2 * np.pi * t / (9 + s0 % 5) + ph0))
    pad = bandpass(pad.astype(np.float32), 250, 1600) * 0.045
    st["ambience"] = ((drone + breath + glass + pad) * (0.55 + 0.45 * lev) + tension).astype(np.float32)

    # --- pulse: heartbeat (lub-dub) with a mid knock so it reads on phones; enters with B, firms in C/D, stops in E
    lub = lambda a: (np.sin(2 * np.pi * np.cumsum(55 + 35 * np.exp(-np.arange(int(0.25 * SR)) / SR * 30)) / SR) * np.exp(-np.arange(int(0.25 * SR)) / SR * 16) * a).astype(np.float32)
    knock = bandpass(_rng(seed, 3).standard_normal(int(0.06 * SR)).astype(np.float32), 600, 1600) * np.exp(-np.arange(int(0.06 * SR)) / SR * 70)
    tb = 0.0
    while tb < total:
        i = min(n - 1, int(tb * SR)); k = sec_at[i]
        amt = {"A": 0.0, "B": 0.55, "C": 0.8, "D": 1.0, "E": 0.0}.get(k, 0.0)
        if amt > 0:
            add(st["pulse"], lub(0.5 * amt), tb); add(st["pulse"], lub(0.32 * amt), tb + 0.2)
            add(st["pulse"], (knock * 0.22 * amt).astype(np.float32), tb); add(st["pulse"], (knock * 0.12 * amt).astype(np.float32), tb + 0.2)
        tb += beat * (1 if k != "D" else 0.5) * 2   # one heartbeat per two beats (twice as often in D)

    # --- motif: the series theme on felt piano; stated in A, answered sparsely in B/C, last incomplete statement in E
    def play_motif(at: float, upto: int = 5, amp: float = 0.22, octave: int = 0):
        x = at
        for semi, beats in MOTIF[:upto]:
            add(st["motif"], piano(hz(semi + 12 * octave), beats * beat + 1.8, amp, seed), x); x += beats * beat
        return x
    starts = {}
    for s, k in zip(tl, secs):
        starts.setdefault(k, s["start"])
    if "A" in starts:
        play_motif(starts["A"] + 0.05, 5, 0.2)
    for s, k in zip(tl, secs):   # sparse answers: a falling pair at the start of each B/C scene that has room
        if k in ("B", "C") and s["end"] - s["start"] > 3.0:
            add(st["motif"], piano(hz(14 if k == "B" else 13), 2.5, 0.12, seed), s["start"] + 0.1)
            add(st["motif"], piano(hz(7 if k == "B" else 6), 3.0, 0.1, seed), s["start"] + 0.1 + beat * 1.5)
    if "E" in starts:
        play_motif(starts["E"] + 0.3, 3, 0.18)   # incomplete on purpose: the story is not over

    # --- metal: bowed swells at each section change (reversed, so they arrive *into* the cut) and under C/D
    prev = None
    for s, k in zip(tl, secs):
        if k != prev and prev is not None:
            sw = metal(hz(12 + (1 if k in "CD" else 0)), 2.6, 0.12)[::-1].copy()
            add(st["metal"], sw, max(0.0, s["start"] - 2.6))
        if k in ("C", "D"):
            add(st["metal"], metal(hz(-5 if k == "C" else -6), s["end"] - s["start"] + 1.0, 0.07), s["start"])
        prev = k

    # --- impacts: explicit hits (word-anchored) and the cliffhanger rise -> impact -> unresolved cluster
    for h in cfg.get("hits", []):
        add(st["impacts"], boom(h.get("gain", 0.5), seed), float(h["at"]))
    d_scenes = [s for s, k in zip(tl, secs) if k == "D"]
    if d_scenes:
        d = d_scenes[0]; hit = float(cfg.get("cliff_at", d["start"]))
        add(st["impacts"], riser(min(3.2, max(1.2, hit - (d["start"] - 3.2))), 0.22, seed), max(0.0, hit - 3.2))
        add(st["impacts"], boom(0.75, seed), hit)
        hang = max(1.5, total - hit)
        cl = sum(piano(hz(s0), hang, 0.07, seed) for s0 in (0, 1, 6))   # root, minor 2nd, tritone: left unresolved
        add(st["motif"], cl.astype(np.float32), hit + 0.05)

    # room and final shape: everything shares one reverb; the score fades with the picture, no abrupt cut, no long tail
    for k in ("motif", "metal", "impacts"):
        st[k] = (st[k] + 0.35 * reverb(st[k], 2.8, seed)).astype(np.float32)
    fade = np.ones(n, np.float32); fl = int(min(3.0, total * 0.1) * SR); fade[-fl:] = np.linspace(1, 0, fl) ** 1.6
    fi = int(0.06 * SR); fade[:fi] *= np.linspace(0, 1, fi)   # 60 ms de-click only: no slow fade-in under the first words
    for k in st:
        st[k] = (st[k][:n] * fade).astype(np.float32)
    return {"stems": st, "sections": secs, "root_hz": root, "bpm": bpm}
